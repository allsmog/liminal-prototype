/* judgment-proof.js · a cut 13 record as a signed packet the existing verifier checks
 * ────────────────────────────────────────────────────────────────────
 * The record in lib/judgment.js says what the operator decided. This module
 * turns that record into a bundle the offline verifier that already ships in
 * receipts/2026-10-06/bundle/verify.mjs can check, byte for byte unchanged.
 * Nothing about verification is new here: same canonical payload, same hash,
 * same Ed25519 signature over the hash string, same file layout.
 *
 * The contract it targets (read from verify.mjs, not restated from memory):
 *   · canonical payload  liminal.founder_packet.v2 · signature_alg ed25519:v1+packet.v2
 *     packet.v3 is NOT used: v3 requires runtime_mode "live" and a provider
 *     execution receipt. This is a fixture, so v3 would be a false claim.
 *   · kind "finding"     so the per-assertion correction (original beside
 *                        corrected) sits INSIDE the signed payload.
 *   · packet_hash        sha256(stableStringify(canonical)) · lowercase hex
 *   · packet_signature   Ed25519 over the UTF-8 bytes of packet_hash
 *   · fingerprint        sha256(raw 32-byte public key)
 *
 * Field mapping (provisional · the founder rules on the vocabulary, see PR):
 *   packet.decision        the cut 13 disposition, verbatim: accept · correct · reject · defer
 *   packet.user_correction the operator's own words (why / reason / waiting for), or null
 *   packet.revisit_at      the defer due date, else null
 *   packet.created_at      the confirm time
 *   packet.runtime_mode    "fixture" (never "live")
 *   packet.context         case, finding, subject, producer, headline
 *   reads[0]               the agent's result: headline, the five assertion
 *                          texts verbatim, each one's evidence ids and support
 *                          level, the agent's stated uncertainty
 *   packet.correction_kind the correction's kind (M1: inner · outer · cross ·
 *                          emergence), null when nothing was corrected
 *   corrections[]          one row when the disposition is correct:
 *                          original assertion text · corrected text · kind
 *
 * What the signature does NOT cover: the support notes, the evidence
 * contents (rows and bodies, only their ids are signed), the adversarial
 * reviewer's action on A5, the record's remaining-uncertainty lines, which
 * evidence the operator opened, the actor label, a typed name, the
 * judged-against line, the record time, the vault
 * id, the pattern watch. packet.v2 has no field for most of these. Carrying them would need a new canonical
 * version, which is a verifier change and out of scope. ABOUT.md and the
 * record both say so.
 *
 * The signing key is a DEMONSTRATION key: Ed25519, generated by WebCrypto in
 * this browser on first use, private half non-extractable, kept in its own
 * IndexedDB database. It proves the bytes were signed by whoever holds that
 * key in this browser. It identifies no person and no organization; this
 * prototype has no sign-in, and nothing outside this browser vouches for it.
 *
 * Pure functions take explicit ids and times so tests can pin golden vectors.
 * No DOM.
 */

import { FIXTURE } from "./judgment.js";

export const PACKET_SCHEMA = "liminal.founder_packet.v2";
export const SIGNATURE_ALG = "ed25519:v1+packet.v2";
export const BUNDLE_FORMAT = "liminal.proof_bundle.v3";
/* the verifier and its readme, shipped in the bundle byte for byte */
export const VERIFIER_FILES = Object.freeze({
  "verify.mjs": "receipts/2026-10-06/bundle/verify.mjs",
  "verify.md": "receipts/2026-10-06/bundle/verify.md",
});
export const KEY_LABEL = "demonstration key · generated in this browser · not tied to a person or organization";

const AGENT_SLUG = "judgment-register";
const KEY_DB = "liminal-judgment-key";
const KEY_STORE = "keys";
const KEY_ID = "demo-ed25519";

/* ─── canonical form · identical to verify.mjs stableStringify ───── */
export function stableStringify(v) {
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  if (Array.isArray(v)) return "[" + v.map(stableStringify).join(",") + "]";
  return "{" + Object.keys(v).sort().map(k => JSON.stringify(k) + ":" + stableStringify(v[k])).join(",") + "}";
}
const hex = (bytes) => [...new Uint8Array(bytes)].map(b => b.toString(16).padStart(2, "0")).join("");
async function sha256(bytes) { return hex(await crypto.subtle.digest("SHA-256", bytes)); }
const utf8 = (s) => new TextEncoder().encode(s);

/**
 * The record as a packet.v2 finding document. Pure.
 * @param {Object} record   a buildRecord() result (lib/judgment.js)
 * @param {Object} ids      { packetId, readId, correctionId } · caller-supplied
 * @param {Object} fixture  the AI result the record judged · supplies the
 *                          evidence links and stated uncertainty, which the
 *                          record's `original` does not copy
 */
export function toPacketDocument(record, { packetId, readId, correctionId }, fixture = FIXTURE) {
  const o = record.original;
  const p = o.producer;
  if (o.caseId !== fixture.caseId || o.findingId !== fixture.findingId) throw new Error("toPacketDocument: record and fixture are different results");
  const confirmedAt = new Date(record.confirmedAt).toISOString();
  const evidenceMap = o.assertions.map(a => ({ assertion: a.id, support: a.support, evidence: fixture.assertions.find(x => x.id === a.id)?.evidence || [] }));
  const packet = {
    id: packetId,
    context: [
      `Case ${o.caseId} · finding ${o.findingId} · ${record.subject}`,
      `Produced by ${p.name} (${p.kind}) · ${p.detail} · ${p.producedAt}`,
      "",
      o.headline,
    ].join("\n"),
    user_correction: record.rationale ?? null,
    chosen_agent: AGENT_SLUG,
    correction_kind: record.change?.kind ?? null,
    runtime_mode: "fixture",
    input_mode: "typed",
    tray_session_id: null,
    source_candidate_id: null,
    pen_hints: null,
    kind: "finding",
    source_packet_id: null,
    corpus_refs: null,
    created_at: confirmedAt,
    decision: record.disposition,
    revisit_at: record.defer?.dueAt ?? null,
    panel_signals: null,
  };
  const read = {
    id: readId,
    packet_id: packetId,
    agent_name: AGENT_SLUG,
    archetype: p.name,
    quoted: o.headline,
    situation: o.assertions.map(a => `${a.id} · ${a.text}`).join("\n"),
    hidden_risk: null,
    next_move: null,
    refusal: null,
    refusal_kind: null,
    ordinal: 0,
    created_at: p.producedAt,
    claim: o.headline,
    evidence_ref: JSON.stringify(evidenceMap),
    confidence: null,
    uncertainty: fixture.uncertainty.join("\n") || null,
    suggested_correction: null,
    packet_impact: null,
  };
  const corrections = record.change ? [{
    id: correctionId,
    packet_id: packetId,
    source_type: "agent_response",
    original: record.change.originalText,
    corrected: record.change.correctedText,
    category: null,
    correction_kind: record.change.kind ?? null,
    created_at: confirmedAt,
  }] : [];
  return { schema: PACKET_SCHEMA, packet, reads: [read], corrections };
}

/** corrections.json · the unsigned narrative copy the verifier cross-checks. Pure. */
export function toCorrectionsDocument(doc) {
  return {
    packet_id: doc.packet.id,
    corrections: doc.corrections.map(c => ({
      id: c.id, packet_id: c.packet_id, source_type: c.source_type, original: c.original,
      category: c.category, reason: c.corrected, correction_kind: c.correction_kind, created_at: c.created_at,
    })),
    correction_count: doc.corrections.length,
    signed_correction_ids: doc.corrections.map(c => c.id),
    integrity: "narrative copy of the signed packet.json corrections; the signed copy inside packet.json is the one that counts",
  };
}

export async function packetHash(doc) { return sha256(utf8(stableStringify(doc))); }

/* ─── keys ───────────────────────────────────────────────────────── */
export async function ed25519Supported() {
  try {
    const k = await crypto.subtle.generateKey({ name: "Ed25519" }, false, ["sign", "verify"]);
    return !!k?.publicKey;
  } catch { return false; }
}

function openKeyDb() {
  return new Promise((resolve, reject) => {
    if (typeof indexedDB === "undefined" || !indexedDB) return reject(new Error("IndexedDB is not available"));
    const req = indexedDB.open(KEY_DB, 1);
    req.onupgradeneeded = () => req.result.createObjectStore(KEY_STORE);
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}
function idb(db, mode, fn) {
  return new Promise((resolve, reject) => {
    const tx = db.transaction(KEY_STORE, mode);
    const req = fn(tx.objectStore(KEY_STORE));
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

/**
 * This browser's demonstration key pair, created on first use. The private
 * key is non-extractable; only the public half ever leaves WebCrypto.
 */
export async function demoKeyPair() {
  const db = await openKeyDb();
  try {
    const have = await idb(db, "readonly", s => s.get(KEY_ID));
    if (have?.privateKey && have?.publicKey) return have;
    const pair = await crypto.subtle.generateKey({ name: "Ed25519" }, false, ["sign", "verify"]);
    const row = { privateKey: pair.privateKey, publicKey: pair.publicKey, createdAt: new Date().toISOString() };
    await idb(db, "readwrite", s => s.put(row, KEY_ID));
    return row;
  } finally { db.close(); }
}

/* ─── signing ────────────────────────────────────────────────────── */
/**
 * Sign a packet document. Returns signature.json content and the fingerprint.
 * `keyPair` is { privateKey, publicKey } CryptoKeys.
 */
export async function signPacket(doc, keyPair) {
  const packet_hash = await packetHash(doc);
  const sig = await crypto.subtle.sign({ name: "Ed25519" }, keyPair.privateKey, utf8(packet_hash));
  const raw = await crypto.subtle.exportKey("raw", keyPair.publicKey);
  const fingerprint = await sha256(raw);
  return {
    packet_hash,
    packet_signature: hex(sig),
    signature_alg: SIGNATURE_ALG,
    canonical_version: doc.schema,
    device_public_key: hex(raw),
    public_key_fingerprint: fingerprint,
  };
}

/** signature.json for a packet this browser could not sign: every proof field blank. */
export function unsignedSignature(doc) {
  return { packet_hash: "", packet_signature: "", signature_alg: "", canonical_version: doc.schema, device_public_key: "", public_key_fingerprint: "" };
}

/**
 * The proof that rides on a stored record. Signs with this browser's
 * demonstration key; if this browser cannot, returns an honestly unsigned
 * proof (the verifier reports it UNVERIFIED, exit 2) and the reason.
 */
export async function proveRecord(record, { ids, keyPair, now = Date.now(), fixture = FIXTURE } = {}) {
  const useIds = ids || { packetId: crypto.randomUUID(), readId: crypto.randomUUID(), correctionId: crypto.randomUUID() };
  const packet = toPacketDocument(record, useIds, fixture);
  const corrections = toCorrectionsDocument(packet);
  const preparedAt = new Date(now).toISOString();
  try {
    const kp = keyPair || await demoKeyPair();
    const signature = await signPacket(packet, kp);
    return { signed: true, packet, signature, corrections, fingerprint: signature.public_key_fingerprint, preparedAt, signError: null };
  } catch (err) {
    const hash = await packetHash(packet).catch(() => null);
    return { signed: false, packet, signature: unsignedSignature(packet), corrections, fingerprint: null, packetHash: hash, preparedAt, signError: String(err?.message || err) };
  }
}

