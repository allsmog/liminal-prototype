export function manifestDocument(proof, files) {
  return { bundle_format: BUNDLE_FORMAT, created_at: proof.preparedAt, app_version: "liminal-prototype · cut 13", packet_id: proof.packet.packet.id, files };
}

/**
 * The bundle's files, in order. `verifier` maps verify.mjs / verify.md to
 * their bytes (fetched by the page, read from disk by tests).
 */
export function bundleFiles(proof, record, verifier) {
  const names = ["packet.json", "signature.json", "corrections.json", "verify.mjs", "verify.md", "ABOUT.md"];
  const json = (v) => utf8(JSON.stringify(v, null, 2) + "\n");
  return [
    { name: "manifest.json", bytes: json(manifestDocument(proof, names)) },
    { name: "packet.json", bytes: json(proof.packet) },
    { name: "signature.json", bytes: json(proof.signature) },
    { name: "corrections.json", bytes: json(proof.corrections) },
    { name: "verify.mjs", bytes: verifier["verify.mjs"] },
    { name: "verify.md", bytes: verifier["verify.md"] },
    { name: "ABOUT.md", bytes: utf8(aboutText(proof, record)) },
  ];
}

